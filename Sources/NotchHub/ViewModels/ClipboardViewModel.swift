import AppKit
import Combine
import Foundation

public enum ClipboardPayload {
    case text(String)
    case image(NSImage)
}

public struct ClipboardEntry: Identifiable {
    public let id = UUID()
    public let date: Date
    public let payload: ClipboardPayload

    public var previewText: String {
        switch payload {
        case .text(let text):
            return text.trimmingCharacters(in: .whitespacesAndNewlines)
        case .image(let image):
            return "Image \(Int(image.size.width))×\(Int(image.size.height))"
        }
    }

    public var isLink: Bool {
        if case .text(let text) = payload {
            let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
            return (t.hasPrefix("http://") || t.hasPrefix("https://")) && !t.contains(" ")
        }
        return false
    }
}

/// Watches the system pasteboard and keeps a short in-memory history.
/// Items flagged by password managers (concealed / transient) are never recorded.
@MainActor
public final class ClipboardViewModel: ObservableObject {
    @Published public private(set) var entries: [ClipboardEntry] = []

    private static let maxEntries = 30
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    public init() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.poll()
            }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let typeNames = Set((pb.types ?? []).map(\.rawValue))
        guard typeNames.isDisjoint(with: Self.privateTypes) else { return }

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if case .text(let existing)? = entries.first?.payload, existing == text { return }
            insert(ClipboardEntry(date: Date(), payload: .text(text)))
        } else if let image = NSImage(pasteboard: pb) {
            insert(ClipboardEntry(date: Date(), payload: .image(image)))
        }
    }

    private func insert(_ entry: ClipboardEntry) {
        entries.insert(entry, at: 0)
        if entries.count > Self.maxEntries {
            entries.removeLast(entries.count - Self.maxEntries)
        }
    }

    public func copy(_ entry: ClipboardEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.payload {
        case .text(let text):
            pb.setString(text, forType: .string)
        case .image(let image):
            pb.writeObjects([image])
        }
        lastChangeCount = pb.changeCount
    }

    public func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
    }

    public func clearAll() {
        entries.removeAll()
    }
}
